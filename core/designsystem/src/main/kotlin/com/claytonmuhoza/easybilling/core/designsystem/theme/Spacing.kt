package com.claytonmuhoza.easybilling.core.designsystem.theme

import androidx.compose.ui.unit.dp

/** Spacing scale shared by every screen, so paddings and gaps stay consistent. */
object Spacing {
    /** Gap between tightly related elements. */
    val extraSmall = 4.dp

    /** Gap between elements of the same group. */
    val small = 8.dp

    /** Default padding and gap. */
    val medium = 16.dp

    /** Padding around a screen section. */
    val large = 24.dp

    /** Gap between distinct sections. */
    val extraLarge = 32.dp
}
